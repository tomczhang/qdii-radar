import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createServer } from 'node:http';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { openStore } from '../server/store.mjs';
import { createApplication } from '../server/index.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'radar-account-browser-'));
const server = createServer();
server.listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
// Reproduce local development with production settings in .env when requested.
const development = process.env.ACCOUNT_SMOKE_DEV === 'true';
process.env.PUBLIC_BASE_URL = development ? 'https://production.example.test' : base;
process.env.PORT = String(server.address().port);
delete process.env.DEV_BASE_URL;
process.env.MAIL_TRANSPORT = 'file';
process.env.ACCOUNT_AUTH_ENABLED = 'true';
const runtime = await createApplication({ store: openStore(dir), startJobs: false, development, hmr: { server } });
server.on('request', runtime.app);
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const output = path.resolve('outputs/local-account');
await fs.mkdir(output, { recursive: true });
const address = 'browser@example.test', password = 'abcd1234', newPassword = 'newp5678';
async function latestLink(purpose) {
  const files = await fs.readdir(path.join(dir, 'mailbox'));
  const messages = await Promise.all(files.map(async name => JSON.parse(await fs.readFile(path.join(dir, 'mailbox', name), 'utf8'))));
  const mail = messages.find(item => item.subject.includes(purpose));
  assert.ok(mail); return mail.text.match(/https?:\/\/[^\s]+/)[0];
}

try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route('https://**/*', route => route.abort());
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.getByRole('link', { name: '登录 / 注册' }).waitFor();
  const guestOwner = (await context.cookies(base)).find(cookie => cookie.name === 'radar_owner')?.value;
  assert.ok(guestOwner);
  await page.goto(`${base}/login?returnTo=${encodeURIComponent('/?page=calculator')}`);
  await page.getByRole('button', { name: '登录', exact: true }).waitFor();
  assert.ok(!(await page.locator('body').innerText()).includes('TomcatTravel'));
  await page.screenshot({ path: path.join(output, 'login-desktop.png'), fullPage: true });
  await page.getByRole('link', { name: '注册', exact: true }).click();
  await page.getByRole('heading', { name: '注册', exact: true }).waitFor();
  await page.getByLabel('昵称', { exact: true }).fill('雷达测试');
  await page.getByLabel('邮箱', { exact: true }).fill(address);
  await page.getByLabel('密码', { exact: true }).fill(password);
  assert.equal(await page.locator('#account-code').count(), 0);
  assert.equal(await page.locator('.account-form input').count(), 3);
  await page.screenshot({ path: path.join(output, 'register-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '注册', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '激活邮件已发送' }).waitFor();
  assert.equal((await (await context.request.get(`${base}/api/auth/session`)).json()).user, null);
  await page.goto(await latestLink('激活'));
  await page.waitForURL(`${base}/?page=calculator`);
  await page.getByRole('heading', { name: '购买计算器', exact: true }).waitFor();
  assert.equal((await context.cookies(base)).find(cookie => cookie.name === 'radar_owner')?.value, guestOwner);
  assert.equal((await context.request.get(`${base}/api/admin/status`)).status(), 401);
  await page.getByRole('button', { name: '关闭条件设置' }).click();
  await page.getByRole('button', { name: '雷达测试', exact: true }).click();
  await page.getByRole('region', { name: '我的账号' }).waitFor();
  assert.equal(await page.getByRole('link', { name: '重设密码' }).getAttribute('href'), '/reset-password');
  await page.screenshot({ path: path.join(output, 'account-desktop.png'), fullPage: true });
  await page.keyboard.press('Escape'); assert.equal(await page.locator('#account-panel').count(), 0);
  await page.reload(); await page.getByRole('button', { name: '雷达测试', exact: true }).waitFor();
  if (await page.getByRole('button', { name: '关闭条件设置' }).isVisible()) await page.getByRole('button', { name: '关闭条件设置' }).click();
  const storage = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }));
  assert.ok(!storage.includes(password) && !storage.includes('password_hash'));
  await page.getByRole('button', { name: '雷达测试', exact: true }).click();
  const [logout] = await Promise.all([page.waitForResponse(response => response.url() === `${base}/api/auth/logout`), page.getByRole('button', { name: '退出登录', exact: true }).click()]);
  assert.equal(logout.status(), 303);
  await page.waitForURL(`${base}/login?loggedOut=1`);
  await page.getByText('已退出登录。', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}/login`);
  await page.getByLabel('邮箱', { exact: true }).fill(address);
  await page.getByLabel('密码', { exact: true }).fill('incorrect-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '邮箱或密码不正确' }).waitFor();
  await page.getByLabel('密码', { exact: true }).fill(password);
  await page.screenshot({ path: path.join(output, 'login-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.waitForURL(`${base}/`);
  await page.getByRole('button', { name: '雷达测试', exact: true }).click();
  await page.screenshot({ path: path.join(output, 'account-mobile.png') });
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  await page.waitForURL(`${base}/login?loggedOut=1`);
  await page.getByRole('link', { name: '忘记密码？' }).click();
  await page.getByRole('heading', { name: '找回密码', exact: true }).waitFor();
  runtime.store.db.prepare('UPDATE local_account_limits SET last_at=last_at-61000').run();
  await page.getByLabel('邮箱', { exact: true }).fill(address);
  await page.getByRole('button', { name: '发送重设密码邮件' }).click();
  await page.getByRole('status').filter({ hasText: '你将收到密码重设邮件' }).waitFor();
  await page.goto(await latestLink('重设'));
  await page.getByRole('heading', { name: '重设密码', exact: true }).waitFor();
  assert.equal(new URL(page.url()).searchParams.has('token'), false, 'token removed from browser address after loading');
  await page.getByLabel('新密码', { exact: true }).fill(newPassword);
  await page.getByLabel('确认密码', { exact: true }).fill(newPassword);
  await page.screenshot({ path: path.join(output, 'reset-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: '重设密码', exact: true }).click();
  await page.waitForURL(/passwordReset=1/);
  await page.getByText('密码已重设，请使用新密码登录。').waitFor();
  await page.getByLabel('邮箱', { exact: true }).fill(address);
  await page.getByLabel('密码', { exact: true }).fill(newPassword);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.waitForURL(`${base}/`);
  await page.getByRole('button', { name: '雷达测试', exact: true }).click();
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  await page.waitForURL(`${base}/login?loggedOut=1`);
  await page.getByRole('link', { name: '免登录继续使用' }).click();
  assert.equal((await context.cookies(base)).find(cookie => cookie.name === 'radar_owner')?.value, guestOwner);
  for (const width of [320, 390, 768, 1024]) {
    await page.setViewportSize({ width, height: 900 });
    for (const route of ['/login', '/register', '/reset-password']) {
      await page.goto(base + route);
      await page.getByLabel('邮箱', { exact: true }).waitFor();
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${route} layout at ${width}px`);
    }
  }
  await page.goto(`${base}/activate?token=invalid`);
  await page.getByRole('alert').filter({ hasText: '链接无效' }).waitFor();
  assert.equal(new URL(page.url()).searchParams.has('token'), false);
  await page.goto(`${base}/login?returnTo=https://evil.test`);
  await page.getByRole('link', { name: '免登录继续使用' }).waitFor();
  assert.equal(await page.getByRole('link', { name: '免登录继续使用' }).getAttribute('href'), '/');
  await page.route('**/api/auth/session', route => route.fulfill({ json: { enabled: false, user: null } }));
  await page.goto(`${base}/register`);
  await page.getByText('账号服务暂未开放，你仍可以免登录使用额度雷达。').waitFor();
  assert.equal(await page.getByRole('button', { name: '注册', exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  console.log('Account browser smoke passed: nickname registration, email activation, password login, reset link, native logout, guest preservation, mobile layouts, disabled service, admin isolation.');
  console.log(`Screenshots: ${output}`);
} finally {
  await browser.close(); await new Promise(resolve => server.close(resolve)); await runtime.close(); await fs.rm(dir, { recursive: true, force: true });
}
