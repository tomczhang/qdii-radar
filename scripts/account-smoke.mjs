import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createServer } from 'node:http';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { openStore } from '../server/store.mjs';
import { createApplication } from '../server/index.mjs';
import { startOidcProvider } from '../test/fixtures/oidc-provider.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
// Different loopback hostnames exercise real cross-site SameSite cookie behavior.
const provider = await startOidcProvider({ hostname: 'localhost' });
const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'radar-account-browser-'));
const server = createServer();
server.listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
process.env.PUBLIC_BASE_URL = base;
process.env.ACCOUNT_CENTER_ISSUER = provider.issuer;
process.env.ACCOUNT_CENTER_CLIENT_ID = provider.clientId;
process.env.ACCOUNT_CENTER_CLIENT_SECRET = provider.clientSecret;
process.env.MAIL_TRANSPORT = 'disabled';
provider.allowedRedirect = `${base}/auth/callback`;
const runtime = await createApplication({ store: openStore(dir), startJobs: false, development: false });
server.on('request', runtime.app);
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const output = path.resolve('outputs/account-center');
await fs.mkdir(output, { recursive: true });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route('https://**/*', route => route.abort());
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.getByRole('link', { name: '登录 / 注册' }).waitFor();
  const guestOwner = (await context.cookies(base)).find(cookie => cookie.name === 'radar_owner')?.value;
  assert.ok(guestOwner);
  await page.goto(`${base}/login?returnTo=${encodeURIComponent('/?page=calculator')}`);
  await page.getByRole('link', { name: '使用 TomcatTravel 账号继续' }).waitFor();
  await page.screenshot({ path: path.join(output, 'login-desktop.png'), fullPage: true });
  await page.getByRole('link', { name: '注册', exact: true }).click();
  await page.getByRole('heading', { name: '注册', exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'register-desktop.png'), fullPage: true });
  await page.getByRole('link', { name: '使用 TomcatTravel 账号注册' }).click();
  await page.waitForURL(`${base}/?page=calculator`);
  await page.getByRole('heading', { name: '购买计算器', exact: true }).waitFor();
  assert.equal((await context.cookies(base)).find(cookie => cookie.name === 'radar_owner')?.value, guestOwner, 'cross-site login must preserve the original anonymous browser identity');
  assert.equal((await context.request.get(`${base}/api/admin/status`)).status(), 401, 'ordinary accounts must not gain admin access');
  await page.getByRole('button', { name: '关闭条件设置' }).click();
  await page.getByRole('button', { name: '雷达用户' }).click();
  await page.getByRole('region', { name: '我的账号' }).waitFor();
  assert.equal(await page.getByRole('link', { name: '管理账号与密码' }).getAttribute('href'), `${provider.issuer}/account/`);
  await page.screenshot({ path: path.join(output, 'account-desktop.png'), fullPage: true });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#account-panel').count(), 0);
  await page.reload();
  await page.getByRole('button', { name: '雷达用户' }).waitFor();
  if (await page.getByRole('button', { name: '关闭条件设置' }).isVisible()) await page.getByRole('button', { name: '关闭条件设置' }).click();
  const storage = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }));
  assert.ok(!storage.includes('fixture-secret') && !storage.includes('fixture-access-token') && !storage.includes('eyJhbGci'));
  await page.getByRole('button', { name: '雷达用户' }).click();
  const [logoutResponse] = await Promise.all([page.waitForResponse(response => response.url() === `${base}/api/auth/logout`), page.getByRole('button', { name: '退出额度雷达', exact: true }).click()]);
  assert.equal(logoutResponse.status(), 303, JSON.stringify({ origin: logoutResponse.request().headers().origin, site: logoutResponse.request().headers()['sec-fetch-site'] }));
  await page.waitForURL(`${base}/login?loggedOut=1`);
  await page.getByText('已退出额度雷达。', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}/login`);
  await page.getByRole('link', { name: '使用 TomcatTravel 账号继续' }).waitFor();
  await page.screenshot({ path: path.join(output, 'login-mobile.png'), fullPage: true });
  await page.getByRole('link', { name: '使用 TomcatTravel 账号继续' }).click();
  await page.waitForURL(`${base}/`);
  await page.getByRole('button', { name: '雷达用户' }).click();
  await page.screenshot({ path: path.join(output, 'account-mobile.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'mobile must not overflow horizontally');
  await page.getByRole('button', { name: '退出统一登录', exact: true }).click();
  await page.waitForURL(`${base}/login?loggedOut=1`);
  await page.getByRole('link', { name: '免登录继续使用' }).click();
  assert.equal((await context.cookies(base)).find(cookie => cookie.name === 'radar_owner')?.value, guestOwner, 'global logout must preserve anonymous subscriptions');
  await page.getByRole('heading', { name: '今日申购额度' }).waitFor();
  for (const width of [320, 768, 1024]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `layout at ${width}px`);
    assert.equal(await page.getByRole('link', { name: '登录 / 注册' }).isVisible(), true);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}/login?error=expired&returnTo=https://evil.test`);
  await page.getByRole('alert').waitFor();
  assert.equal(await page.getByRole('link', { name: '免登录继续使用' }).getAttribute('href'), '/');
  await page.route('**/api/auth/session', route => route.fulfill({ json: { enabled: false, user: null } }));
  await page.goto(`${base}/register`);
  await page.getByText('账号登录尚未开放，当前可以免登录使用额度雷达。').waitFor();
  assert.equal(await page.getByRole('button', { name: '使用 TomcatTravel 账号注册' }).isDisabled(), true);
  await page.screenshot({ path: path.join(output, 'disabled-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Account browser smoke passed: registration/login round trip, return page, reload, native local/global logout, desktop/mobile, expiry error, disabled service and token isolation.');
  console.log(`Screenshots: ${output}`);
} finally {
  await browser.close(); await new Promise(resolve => server.close(resolve)); await runtime.close(); await provider.close(); await fs.rm(dir, { recursive: true, force: true });
}
