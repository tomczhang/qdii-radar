import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openStore} from '../server/store.mjs';
import {createApplication} from '../server/index.mjs';
import {DASHBOARD_CACHE_KEY} from '../src/dashboard-cache.mjs';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const dir=await mkdtemp(join(tmpdir(),'radar-dashboard-cache-'));
const runtime=await createApplication({store:openStore(dir),startJobs:false,development:false});
const server=runtime.app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
const base=`http://127.0.0.1:${server.address().port}`,browser=await chromium.launch({channel:'chrome',headless:true});
try {
 const context=await browser.newContext({timezoneId:'America/Los_Angeles'}),page=await context.newPage();
 const fixture=await(await page.request.get(base+'/api/dashboard')).json();
 fixture.meta={...fixture.meta,dailySyncTime:'07:30',updatedAt:'2026-10-19T00:00:00.000Z',lastRun:{status:'success',startedAt:'2026-10-19T07:30:00+08:00'}};
 let calls=0,fail=false;const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await context.route('**/api/dashboard',async route=>{calls++;await route.fulfill(fail?{status:503,json:{error:'测试刷新失败'}}:{json:fixture});});
 const start=new Date('2026-10-19T16:29:00+08:00');
 await page.clock.install({time:start});await page.clock.pauseAt(start);await page.goto(base,{waitUntil:'networkidle'});
 assert.equal(calls,1);
 const saved=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),DASHBOARD_CACHE_KEY);
 assert.equal(saved.expiresAt,Date.parse('2026-10-19T16:30:00+08:00'));
 await page.reload({waitUntil:'networkidle'});assert.equal(calls,1,'reload must not fetch a fresh dashboard');
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')));assert.equal(calls,1);
 const tab=await context.newPage();await tab.clock.install({time:start});await tab.clock.pauseAt(start);await tab.goto(base,{waitUntil:'networkidle'});
 assert.equal(calls,1,'new tab shares local cache');await tab.close();
 assert.equal((await page.evaluate(key=>JSON.parse(localStorage.getItem(key)),DASHBOARD_CACHE_KEY)).savedAt,saved.savedAt,'reading cannot extend expiry');
 fixture.meta.lastRun={status:'running',startedAt:'2026-10-19T16:30:00+08:00',phase:'market',completed:1,total:71};
 let response=page.waitForResponse(r=>r.url().endsWith('/api/dashboard'));
 await page.clock.fastForward(60000);await response;await page.getByText('正在同步',{exact:true}).waitFor();assert.equal(calls,2);
 fixture.meta.lastRun={status:'success',startedAt:'2026-10-19T16:30:00+08:00'};
 response=page.waitForResponse(r=>r.url().endsWith('/api/dashboard'));await page.clock.fastForward(15000);await response;
 await page.getByText('正在同步',{exact:true}).waitFor({state:'hidden'});assert.equal(calls,3);
 await page.reload({waitUntil:'networkidle'});assert.equal(calls,3);
 await page.clock.setSystemTime(new Date('2026-10-20T07:35:00+08:00'));
 response=page.waitForResponse(r=>r.url().endsWith('/api/dashboard'));await page.evaluate(()=>window.dispatchEvent(new Event('focus')));await response;assert.equal(calls,4,'wake checks absolute expiry');
 await page.evaluate(key=>localStorage.setItem(key,'broken-json'),DASHBOARD_CACHE_KEY);
 await page.reload({waitUntil:'networkidle'});assert.equal(calls,5,'corrupt storage falls back to server');
 const beforeFailure=await page.evaluate(key=>localStorage.getItem(key),DASHBOARD_CACHE_KEY);
 fail=true;await page.clock.setSystemTime(new Date('2026-10-20T16:31:00+08:00'));
 response=page.waitForResponse(r=>r.url().endsWith('/api/dashboard'));await page.evaluate(()=>window.dispatchEvent(new Event('focus')));await response;
 await page.getByText('测试刷新失败',{exact:true}).waitFor();assert.equal(calls,6);
 assert.equal(await page.evaluate(key=>localStorage.getItem(key),DASHBOARD_CACHE_KEY),beforeFailure,'failure cannot renew stale cache');
 fail=false;response=page.waitForResponse(r=>r.url().endsWith('/api/dashboard'));await page.clock.fastForward(15000);await response;
 await page.getByText('测试刷新失败',{exact:true}).waitFor({state:'hidden'});assert.equal(calls,7);
 assert.deepEqual(errors,[]);
 console.log('Dashboard cache passed: reload/new-tab hits, fixed Beijing expiry in US timezone, scheduled refresh, sync polling, wake-up, corruption and failure retry.');
} finally {await browser.close();await new Promise(resolve=>server.close(resolve));await runtime.close();await rm(dir,{recursive:true,force:true});}
